/**
 * Intelligent Scripture Search (RAG Engine):
 * Matches explicit verse citations (e.g. "2.47", "18.66", "chapter 9 verse 26"),
 * thematic keywords, Sanskrit phrases, and concept tokens.
 */
export const searchGitaVerses = (queryText, topK = 3) => {
  if (!queryText || !queryText.trim()) {
    return gitaVerses.slice(0, topK);
  }

  const cleanQuery = queryText.toLowerCase().trim();
  const tokens = cleanQuery.split(/[\s,?.!-]+/).filter(t => t.length > 2);

  // 1. Direct Chapter & Verse match (e.g. "2.47", "BG 18.66", "chapter 4 verse 7")
  const refMatch = cleanQuery.match(/(?:chapter\s*|bg\s*)?(\d{1,2})[\s.:]+(\d{1,2})/i);
  if (refMatch) {
    const ch = parseInt(refMatch[1], 10);
    const vr = parseInt(refMatch[2], 10);
    const directHit = gitaVerses.find(v => v.chapter === ch && (v.verse === vr || v.ref.includes(`${ch}.${vr}`)));
    if (directHit) {
      const rest = gitaVerses.filter(v => v !== directHit);
      return [directHit, ...rest.slice(0, topK - 1)];
    }
  }

  // 2. Multi-weight scoring
  const scored = gitaVerses.map(verse => {
    let score = 0;

    // Check keywords (high weight)
    verse.keywords.forEach(kw => {
      if (cleanQuery.includes(kw)) score += 5;
      tokens.forEach(tok => {
        if (kw.includes(tok)) score += 2.5;
      });
    });

    // Check translation words
    const transLower = verse.translation.toLowerCase();
    tokens.forEach(tok => {
      if (transLower.includes(tok)) score += 2;
    });

    // Check theme
    const themeLower = verse.theme.toLowerCase();
    tokens.forEach(tok => {
      if (themeLower.includes(tok)) score += 3;
    });

    // Check transliteration
    const transLitLower = (verse.transliteration || '').toLowerCase();
    tokens.forEach(tok => {
      if (transLitLower.includes(tok)) score += 2.5;
    });

    return { verse, score };
  });

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, topK).map(item => item.verse);
};
